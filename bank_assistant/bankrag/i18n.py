# Strings the browser-side scripts need.
JS_KEYS = [k for k in STRINGS if not k.startswith(("setup_", "login_"))] + ["login_title"]


def translate(key, lang, **kwargs):
    pair = STRINGS.get(key)
    if pair is None:
        return key
    text = pair[0] if lang == "ar" else pair[1]
    return text.format(**kwargs) if kwargs else text


def js_strings(lang):
    return {k: translate(k, lang) for k in JS_KEYS}
